def header(f, width, active=0, compact=False):
    """Гостевая шапка (D-CHROME). Возвращает нижнюю границу."""
    f.put("logo", 10, 6, 15, 15, text="🔥")
    f.label(28, 6, 64, "HeatCalc", tpl="brand", h=17)

    labels = NAV_SHORT if compact else NAV
    widths = [108, 122, 92] if compact else [124, 150, 112]
    x = 104
    for i, (lab, w) in enumerate(zip(labels, widths)):
        if i == active:
            f.put("mi-active", x, 2, w + 16, 24)
        f.label(x + 8, 6, w, lab, tpl="mi")
        x += w + (16 if i == active else 0) + 20

    plan = ([(T["guest_mode_short"], 72), (T["open_file_short"], 116),
             (T["save_file_short"], 124), ("?", 28)] if compact else
            [(T["guest_mode"], 124), (T["open_file"], 182),
             (T["save_file"], 186), ("? Инструкция", 106), ("⏻ Выход", 76)])
    total = sum(w for _, w in plan) + 8 * (len(plan) - 1)
    x = width - 10 - total
    for i, (lab, w) in enumerate(plan):
        if i == 0:
            f.label(x, 6, w, lab, tpl="project", h=14)
        else:
            f.button(x, 3, w, lab)
        x += w + 8
    return 28


