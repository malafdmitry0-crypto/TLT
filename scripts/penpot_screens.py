def elec_base(name, y, banner=None, banner_kind="info", rows=None,
              extra=None, width=1440, height=560, add_disabled=False,
              active_tab="samreg", counts=(0, 2), manual_guard=False,
              banner_actions=(), row_action_col=0, cols=None, annotate=None):
    W, H = width, height
    f = FrameBuilder(name, 0, y, W, H)
    top = header(f, W, active=1, compact=W < 1200)

    # панель вариантов ЭР
    x = G
    for i in range(1, 6):
        x = f.chip(x, top + 8, 58, f"ЭР{i}", tpl="type-btn")
    add_x = x + 6
    f.chip(add_x, top + 8, 168, "Добавить новый расчёт")
    if add_disabled:
        f.put("trow", add_x, top + 8, 168, 22, fill="#f2f3f5", opacity=0.75)
        f.layer = 1                       # всплывающая подсказка — поверх экрана
        f.put("mode-tag", add_x, top + 34, 210, 20, fill="#1f2329", opacity=0.9)
        f.label(add_x + 8, top + 38, 194, "Максимум 5 вариантов расчёта",
                on_primary=True)
        f.layer = 0
    f.button(W - G - 244, top + 8, 244, "🗎 Сформировать спецификацию", tpl="next-btn", h=24)
    y2 = top + 42

    # сводки: активна только Самрег; Резистив/Скин — «Скоро» (R2 + EQ5: по ТЗ)
    cards = [("Саммари Самрег", False), ("Саммари Резистив · Скоро", True),
             ("Саммари Скин · Скоро", True), ("Саммари Итого", False)]
    cw = (W - 2 * G - 3 * 12) // 4
    for i, (title, dim) in enumerate(cards):
        cx = 10 + i * (cw + 12)
        f.put("trow" if dim else "thead", cx, y2, cw, 96)
        f.label(cx + 10, y2 + 8, cw - 20, title)
        if not dim:
            for j, (k, v) in enumerate([("Объектов", "2"), ("Длина кабеля, м", "310"),
                                        ("Секций", "5")]):
                f.label(cx + 10, y2 + 30 + j * 18, cw - 70, k)
                f.label(cx + cw - 56, y2 + 30 + j * 18, 46, v)
    y2 += 108

    # вкладки распределения (счётчики и активная — параметры состояния)
    un, sr = counts
    x = G
    tabs = [(f"Нераспределённые объекты  {un}", 196, active_tab == "unassigned"),
            (f"Самрег  {sr}", 96, active_tab == "samreg"),
            ("Резистив · Скоро", 122, False), ("Скин · Скоро", 100, False)]
    for lab, w, is_active in tabs:
        if is_active:
            f.put("mi-active", x - 2, y2 - 2, w + 4, 26)
        x = f.chip(x, y2, w, lab, tpl="type-btn")
    f.label(G, y2 + 32, 480, T["only_selfreg"])
    y2 += 56

    # строка управления: 230 В read-only, нитки 1…3, защита ручных марок
    cx = 10
    cx = f.label_row(cx, y2 + 5, "U, В:") + 8
    f.put("hbtn", cx, y2, 56, 22)
    f.label(cx + 8, y2 + 4, 40, "230")
    cx = f.label_row(cx + 64, y2 + 5, "норматив / система · только чтение") + 18
    cx = f.label_row(cx, y2 + 5, "Ниток:") + 8
    f.put("hbtn", cx, y2, 70, 22)
    f.label(cx + 8, y2 + 4, 54, "◂  1…3  ▸")
    cx += 70 + 18
    if manual_guard:
        f.put("row-cb", cx, y2 + 5, 13, 13)
        f.label_row(cx + 18, y2 + 5, "Не перезаписывать ручные марки")
    f.button(W - 300, y2, 140, "⟳ Пересчитать всё", tpl="recalc-all", h=22)
    f.button(W - G - 156, y2, 156, "⊞ Настройки проекта", h=22)
    y2 += 34

    if banner:
        y2 = f.alert(G, y2, W - 2 * G, banner, kind=banner_kind,
                     actions=banner_actions) + 4

    cols = (cols or ELEC_COLS) + ([("", row_action_col)] if row_action_col else [])
    f.table(G, y2, W - 2 * G, cols, rows if rows is not None else ROW_HAPPY,
            empty_rows=2)
    if extra:
        extra(f, y2)
    return f.finish(annotate)


