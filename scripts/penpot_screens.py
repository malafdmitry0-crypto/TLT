def heat_frame(name, y, mode="base", annotate=None, forms=True, rows=None,
               banner=None, banner_kind="info", banner2=None, banner2_kind="warn",
               blocks=None, chips=None, cols=None, layers=None):
    # 1280 — минимальная поддерживаемая ширина (решение владельца 2026-08-05,
    # поддержка 1000 снята). Кадр рисуем на худшем случае: сойдётся здесь —
    # сойдётся на 1440 и 1920.
    W = 1280
    H = {"base": 420, "group": 460, "columns": 460, "file-open": 460,
         "next-errors": 460, "import": 460}[mode] + (330 if forms else 0)
    f = FrameBuilder(name, 0, y, W, H)
    top = header(f, W, active=0)
    y2 = top + 8

    if forms:
        # ДВЕ формы (Q1, бриф §6.3): параметры спецификации — в модалке настроек.
        # Панели растут от центра к краям: зазор в середине фиксирован, обе
        # упираются в поля страницы. Левая шире — у теплопотерь больше полей (2:1).
        GAP = 16
        avail = W - 2 * G - GAP
        left_w = round(avail * 0.63)
        right_w = avail - left_w
        col2 = G + left_w + GAP
        blocks = blocks or [[(HEAT_TEXT, 2, 118, KIND_OPTS), (HEAT_NUM, 3, 132, KIND_OPTS)],
                            [(CABLE_FIELDS, 2, 86, {"unit_suffix": True, "kinds": FIELD_KIND})]]
        left_b = f.form_panel(G, y2, left_w, "РАСЧЁТ ТЕПЛОПОТЕРЬ", blocks[0],
                              table_spec=("Слои изоляции", LAYER_COLS,
                                          layers or LAYER_ROWS))
        cab_b = f.form_panel(col2, y2, right_w, "АЛГОРИТМ ВЫБОРА КАБЕЛЯ", blocks[1])
        # подпись-пояснение про 230 В снята решением владельца (бриф §6.2);
        # само требование read-only остаётся — поле не редактируется
        band = max(left_b, cab_b)
        y2 = f.alert(G, band + 10, W - 2 * G,
                     "Класс взрывозащиты, коэффициенты и способ формирования — "
                     "в «Настройки» на шаге «Спецификация», не на объекте",
                     kind="info") + 4

    x = G
    for lab, w in (chips or (("Трубопровод: 3", 128), ("Резервуар: 0", 118),
                             ("Все: 3", 92))):
        x = f.chip(x, y2, w, lab)
    f.chip(x, y2, 78, "Пол · Скоро")
    f.button(W - G - 258, y2, 258, "Далее → Электротехнический расчёт",
             tpl="next-btn", h=24)
    y2 += 34

    # именованные кнопки панели объектов (§5.5–5.9)
    x = G
    for lab, w in (("⬆ Загрузить из Excel", 156), ("⧉ Добавить на основании", 172),
                   ("🗑 Удалить", 100), ("✎ Групповая корректировка", 190),
                   ("⊞ Настройки отображения", 182)):
        x = f.button(x, y2, w, lab)
    y2 += 30
    f.label(G, y2, 460, "Дополнительные столбцы доступны через настройки отображения")
    y2 += 22

    if banner:
        y2 = f.alert(G, y2, W - 2 * G, banner, kind=banner_kind)
    if banner2:
        y2 = f.alert(G, y2, W - 2 * G, banner2, kind=banner2_kind)

    y2 = f.table(G, y2, W - 2 * G, cols or HEAT_COLS,
                 rows if rows is not None else HEAT_ROWS, empty_rows=1)
    f.label(G, y2 + 8, 200, "Выбрано: 1 из 3")
    f.label(W - G - 250, y2 + 8, 250, "Отображено 3 из 3 объектов")

    if mode == "group":
        f.modal(W // 2, 120, 560, 250, "Групповая корректировка",
                ["Выбрано объектов: 2",
                 "Параметр:  Толщина изоляции, мм        ▾",
                 "Новое значение:  80",
                 "За одну операцию изменяется один параметр (§5.8).",
                 "Недопустимые для части объектов значения будут показаны списком."],
                [("Отмена", 100, "hbtn"), ("Применить", 130, "next-btn")],
                frame_w=W, frame_h=H)
    if mode == "columns":
        f.modal(W // 2, 120, 520, 260, "Настройки отображения",
                ["☑ Наименование      ☑ Длина, м        ☑ Диаметр, мм",
                 "☑ Толщина изоляции  ☑ Материал        ☑ Токр, °C",
                 "☐ Скорость ветра    ☐ Лок. элементы   ☐ Kзап",
                 "☑ Теплопотери       ☑ Статус",
                 "Чекбокс выбора строки скрыть нельзя.",
                 "Настройки действуют в рамках текущей сессии (§5.9)."],
                [("По умолчанию", 140, "hbtn"), ("Применить", 130, "next-btn")],
                frame_w=W, frame_h=H)
    if mode == "file-open":
        f.modal(W // 2, 120, 540, 210, "Заменить текущий проект?",
                ["Открытие файла проекта заменит текущий проект (3 объекта)",
                 "данными из файла. Несохранённые изменения будут потеряны.",
                 "При ошибке разбора файла текущий проект останется без изменений.",
                 "Чтобы не потерять работу — сначала «Сохранить проект в файл»."],
                [("Отмена", 100, "hbtn"), ("Заменить и открыть", 170, "next-btn")],
                frame_w=W, frame_h=H)
    return f.finish(annotate)


